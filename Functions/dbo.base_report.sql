IF OBJECT_ID('dbo.base_report') IS NOT NULL
    DROP FUNCTION [dbo].[base_report];
GO

CREATE FUNCTION [dbo].[base_report] 
(	
	@FIRSTDAY datetime,
	@SID int, 
	@GROUP_ID int,
	@VIEW_LEVEL int,
	@IS_ABBREV int = 0,
	@WOODVAR int,
	@IRONVAR int
)
RETURNS TABLE 
AS
RETURN 
(

/*  @WOODVAR
1 - drivers
2 - hybrids
3 - fairway w/ hyb
4 - fairway w/o hyb
other - all

@IRONVAR
1 - utility
other - all
*/
	
	

with cte_main as (
SELECT a.PLAYERNAME as pname, SequenceNum as LINE_NUMBER, CATEGORY, EXTRA
FROM [Player_Master].[All] a
inner JOIN [Player_master].PLAYERNAMES c on a.PLAYERNAME = c.PLAYERNAME AND a.SID = c.SID AND a.[FIRST DAY] = c.FIRSTDAY
CROSS JOIN (select top 7 SequenceNum from LKP.Sequence order by SequenceNum) q
WHERE [FIRST DAY] = @FIRSTDAY AND a.SID = @SID),



BALLTABLE AS (
SELECT 1 as BALLNUMBER, d.PLAYERNAME, 
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(a.[Mfgr Abbrev], a.[Mfgr Descr]) ELSE a.[Mfgr Descr] END AS BALLBRAND, DBALLBRAND,
(CASE WHEN (a.[Mfgr Descr] IN (SELECT COMPANY FROM LKP.Company_Groups WHERE GROUP_ID = @GROUP_ID)) THEN b.[Model Descr] ELSE (SELECT CASE WHEN @VIEW_LEVEL = 0 THEN b.[Model Descr] WHEN @VIEW_LEVEL = 1 THEN b.[Model Lvl1] WHEN @VIEW_LEVEL = 2 THEN b.[Model Lvl2] WHEN @VIEW_LEVEL = 3 THEN b.[Model Lvl3] END) END) AS BALLMODEL, DBALLMODEL,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(e.[Mfgr Abbrev], e.[Mfgr Descr]) ELSE e.[Mfgr Descr] END AS GLOVEBRAND, DGLOVEBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(f.[Mfgr Abbrev], f.[Mfgr Descr]) ELSE f.[Mfgr Descr] END AS SHOEBRAND, DSHOEBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(g.[Mfgr Abbrev], g.[Mfgr Descr]) ELSE g.[Mfgr Descr] END AS HATBRAND, DHEADGEARBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(zzz.[Mfgr Abbrev], zzz.[Mfgr Descr]) ELSE zzz.[Mfgr Descr] END AS SHIRTBRAND, DSHIRTBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(abc.[Mfgr Abbrev], abc.[Mfgr Descr]) ELSE abc.[Mfgr Descr] END AS CADDYHEADBRAND, DCADDYHEADBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(yyy.[Mfgr Abbrev], yyy.[Mfgr Descr]) ELSE yyy.[Mfgr Descr] END AS GLASSESBRAND, DGLASSESBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(qqq.[Mfgr Abbrev], qqq.[Mfgr Descr]) ELSE qqq.[Mfgr Descr] END AS RAINGEARBRAND, DRAINGEARBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(h.[Mfgr Abbrev], h.[Mfgr Descr]) ELSE h.[Mfgr Descr] END AS BAGBRAND, DBAGBRAND,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(i.[Mfgr Abbrev], i.[Mfgr Descr]) ELSE i.[Mfgr Descr] END AS SPIKEBRAND, DSPIKEBRAND,
(CASE WHEN (i.[Mfgr Descr] IN (SELECT COMPANY FROM LKP.Company_Groups WHERE GROUP_ID = @GROUP_ID)) THEN j.[Model Descr] ELSE (SELECT CASE WHEN @VIEW_LEVEL = 0 THEN j.[Model Descr] WHEN @VIEW_LEVEL = 1 THEN j.[Model Lvl1] WHEN @VIEW_LEVEL = 2 THEN j.[Model Lvl2] WHEN @VIEW_LEVEL = 3 THEN j.[Model Lvl3] END) END) AS SPIKEMODEL, DSPIKEMODEL
FROM [Player_Master].[All] d
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] a ON BALLBRAND = a.[Mfgr Code] 
LEFT OUTER JOIN [LKP].[Model Codes and Descr] b ON BALLMODEL = b.[Model Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] e ON GLOVEBRAND = e.[Mfgr Code] 
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] f ON SHOEBRAND = f.[Mfgr Code] 
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] g ON HEADGEARBRAND = g.[Mfgr Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] zzz ON SHIRTBRAND = zzz.[Mfgr Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] abc ON CADDYHEADBRAND = abc.[Mfgr Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] yyy ON GLASSESBRAND = yyy.[Mfgr Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] qqq ON RAINGEARBRAND = qqq.[Mfgr Code]
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] h ON BAGBRAND = h.[Mfgr Code] 
LEFT OUTER JOIN [LKP].[Manufacturer Codes and Desc] i ON SPIKEBRAND = i.[Mfgr Code] 
LEFT OUTER JOIN [LKP].[Model Codes and Descr] j ON SPIKEMODEL = j.[Model Code]
WHERE [FIRST DAY] = @FIRSTDAY AND d.SID = @SID
),


IRONTABLE as 
(select * from (
SELECT row_number() OVER(PARTITION BY Name ORDER BY c.[PKey] ASC) as IRONNUMBER, [Iron Club Code],
Name as PLAYERNAME, [Iron Club Code] AS IRONCLUBCODE, DCLUBCODE, 
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(a.[Mfgr Abbrev], a.[Mfgr Descr]) ELSE a.[Mfgr Descr] END AS IRONBRAND, DBRANDCODE, 
(CASE WHEN (a.[Mfgr Descr] IN (SELECT COMPANY FROM LKP.Company_Groups with (nolock) WHERE GROUP_ID = @GROUP_ID)) THEN b.[Model Descr] ELSE (SELECT CASE WHEN @VIEW_LEVEL = 0 THEN b.[Model Descr] WHEN @VIEW_LEVEL = 1 THEN b.[Model Lvl1] WHEN @VIEW_LEVEL = 2 THEN b.[Model Lvl2] WHEN @VIEW_LEVEL = 3 THEN b.[Model Lvl3] END) END) AS IRONMODEL, DMODELCODE, 
NULL AS IRONTYPE, NULL AS DTYPECODE
FROM [Player_Master].[Iron Detail] c
LEFT OUTER JOIN Player_Master.PLAYERNAMES d ON c.[Survey ID] = d.SID and c.Name = d.PLAYERNAME and c.[First Day] = d.FIRSTDAY 
LEFT OUTER JOIN LKP.[Manufacturer Codes and Desc] a ON [Iron Brand Code] = a.[Mfgr Code]
LEFT OUTER JOIN LKP.[Model Codes and Descr] b ON [Iron Model Code] = b.[Model Code]
WHERE [First Day] = @FIRSTDAY AND [Survey ID] = @SID) z
where @IRONVAR = 0 Or (@IRONVAR = 1 And [Iron Club Code] like '%^%')
),



WOODTABLE AS (
SELECT  row_number() OVER(PARTITION BY Name ORDER BY [PKey] ASC) as WOODNUMBER,
name as PLAYERNAME, 
[Wood Club Code] AS WOODCLUBCODE, DCLUBCODE,
CASE WHEN @IS_ABBREV = 1 THEN COALESCE(a.[Mfgr Abbrev], a.[Mfgr Descr]) ELSE a.[Mfgr Descr] END AS WOODBRAND, DBRANDCODE,
(CASE WHEN (a.[Mfgr Descr] IN (SELECT COMPANY FROM LKP.Company_Groups with (nolock) WHERE GROUP_ID = @GROUP_ID)) THEN b.[Model Descr] ELSE (SELECT CASE WHEN @VIEW_LEVEL = 0 THEN b.[Model Descr] WHEN @VIEW_LEVEL = 1 THEN b.[Model Lvl1] WHEN @VIEW_LEVEL = 2 THEN b.[Model Lvl2] WHEN @VIEW_LEVEL = 3 THEN b.[Model Lvl3] END) END) AS WOODMODEL, DMODELCODE,
