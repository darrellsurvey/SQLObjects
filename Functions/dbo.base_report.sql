--WOODSHAFTMFGR, DWOODSHAFTMFGR, WOODSHAFTBRAND, DWOODSHAFTBRAND, WOODSHAFTMODEL, DWOODSHAFTMODEL, WOODSHAFTFLEX, DWOODSHAFTFLEX, WOODSHAFTMATL, DWOODSHAFTMATERIAL,
--WOODGRIPMFGR, DWOODGRIPMFGR, WOODGRIPBRAND, DWOODGRIPBRAND, WOODGRIPMODEL, DWOODGRIPMODEL, WOODGRIPMATL, DWOODGRIPMATERIAL,
--PUTTERBRAND, DPUTTERBRANDCODE, PUTTERMODEL, DPUTTERMODELCODE, PUTTERSIZE, DPUTTERSIZECODE,
--PUTTERGRIPMFGR, DPUTTERGRIPMFGR, PUTTERGRIPBRAND, DPUTTERGRIPBRAND, PUTTERGRIPMODEL, DPUTTERGRIPMODEL, PUTTERGRIPMATL, DPUTTERGRIPMATERIAL,
--GLOVEBRAND, DGLOVEBRAND, SHOESBRAND, DSHOEBRAND, HATBRAND, DHEADGEARBRAND, BAGBRAND, DBAGBRAND, SHIRTBRAND, DSHIRTBRAND,CADDYHEADBRAND, DCADDYHEADBRAND,GLASSESBRAND, DGLASSESBRAND,RAINGEARBRAND, DRAINGEARBRAND, SPIKEBRAND, DSPIKEBRAND, SPIKEMODEL, DSPIKEMODEL


cte1 as (
select pname,
		LINE_NUMBER,
		coalesce(irontable.PLAYERNAME, WEDGETABLE.PLAYERNAME, WOODTABLE.PLAYERNAME) AS PLAYERNAME,
		CATEGORY, EXTRA, BALLBRAND, DBALLBRAND, BALLMODEL, DBALLMODEL,
		IRONCLUBCODE, IRONTABLE.DCLUBCODE AS DIRONCLUBCODE, IRONBRAND, IRONTABLE.DBRANDCODE AS DIRONBRANDCODE, IRONMODEL, IRONTABLE.DMODELCODE AS DIRONMODELCODE,IRONTABLE.IRONTYPE AS IRONSIZE, IRONTABLE.DTYPECODE AS DIRONSIZECODE,
		IRONSHAFTMFGR, DIRONSHAFTMFGR, IRONSHAFTBRAND, DIRONSHAFTBRAND, IRONSHAFTMODEL, DIRONSHAFTMODEL, IRONSHAFTFLEX, DIRONSHAFTFLEX, IRONSHAFTMATL, DIRONSHAFTMATERIAL,
		IRONGRIPMFGR, DIRONGRIPMFGR, IRONGRIPBRAND, DIRONGRIPBRAND, IRONGRIPMODEL, DIRONGRIPMODEL, IRONGRIPMATL, DIRONGRIPMATERIAL,
		WEDGECLUBCODE, WEDGETABLE.DCLUBCODE AS DWEDGECLUBCODE, WEDGEBRAND, WEDGETABLE.DBRANDCODE AS DWEDGEBRANDCODE, WEDGEMODEL, WEDGETABLE.DMODELCODE AS DWEDGEMODELCODE, WEDGETYPE, WEDGETABLE.DTYPECODE AS DWEDGETYPE,
		WEDGESHAFTMFGR, DWEDGESHAFTMFGR, WEDGESHAFTBRAND, DWEDGESHAFTBRAND, WEDGESHAFTMODEL, DWEDGESHAFTMODEL, WEDGESHAFTFLEX, DWEDGESHAFTFLEX, WEDGESHAFTMATL, DWEDGESHAFTMATERIAL,
		WEDGEGRIPMFGR, DWEDGEGRIPMFGR, WEDGEGRIPBRAND, DWEDGEGRIPBRAND, WEDGEGRIPMODEL, DWEDGEGRIPMODEL, WEDGEGRIPMATL, DWEDGEGRIPMATERIAL,
		WOODCLUBCODE, WOODTABLE.DCLUBCODE AS DWOODCLUBCODE, WOODBRAND, WOODTABLE.DBRANDCODE AS DWOODBRANDCODE, WOODMODEL, WOODTABLE.DMODELCODE AS DWOODMODELCODE, WOODSIZE, WOODTABLE.DSIZECODE AS DWOODSIZECODE, WOODMATL, DMATERIAL,
		WOODSHAFTMFGR, DWOODSHAFTMFGR, WOODSHAFTBRAND, DWOODSHAFTBRAND, WOODSHAFTMODEL, DWOODSHAFTMODEL, WOODSHAFTFLEX, DWOODSHAFTFLEX, WOODSHAFTMATL, DWOODSHAFTMATERIAL,
		WOODGRIPMFGR, DWOODGRIPMFGR, WOODGRIPBRAND, DWOODGRIPBRAND, WOODGRIPMODEL, DWOODGRIPMODEL, WOODGRIPMATL, DWOODGRIPMATERIAL,
		PUTTERBRAND, PUTTERTABLE.DBRANDCODE AS DPUTTERBRANDCODE, PUTTERMODEL, PUTTERTABLE.DMODELCODE AS DPUTTERMODELCODE, PUTTERSIZE, PUTTERTABLE.DSIZECODE AS DPUTTERSIZECODE,
		PUTTERGRIPMFGR, DPUTTERGRIPMFGR, PUTTERGRIPBRAND, DPUTTERGRIPBRAND, PUTTERGRIPMODEL, DPUTTERGRIPMODEL, PUTTERGRIPMATL, DPUTTERGRIPMATERIAL,
		GLOVEBRAND, DGLOVEBRAND, SHOEBRAND AS SHOESBRAND, DSHOEBRAND, HATBRAND, DHEADGEARBRAND, BAGBRAND, DBAGBRAND,
		SHIRTBRAND, DSHIRTBRAND,CADDYHEADBRAND, DCADDYHEADBRAND,GLASSESBRAND, DGLASSESBRAND,RAINGEARBRAND, DRAINGEARBRAND, SPIKEBRAND, DSPIKEBRAND, SPIKEMODEL, DSPIKEMODEL,
		IRONSHAFTCLUBCODE, DIRONSHAFTCLUBCODE, WOODSHAFTCLUBCODE, DWOODSHAFTCLUBCODE, WEDGESHAFTCLUBCODE, DWEDGESHAFTCLUBCODE,
		IRONGRIPCLUBCODE, DIRONGRIPCLUBCODE, WOODGRIPCLUBCODE, DWOODGRIPCLUBCODE, WEDGEGRIPCLUBCODE, DWEDGEGRIPCLUBCODE, PUTTERGRIPCLUBCODE, DPUTTERGRIPCLUBCODE,
		ROW_NUMBER() over(order by extra, pname, LINE_NUMBER) as ROW_ORDER
FROM cte_main
left outer join IRONTABLE ON cte_main.pname = IRONTABLE.PLAYERNAME AND IRONNUMBER = LINE_NUMBER
left OUTER JOIN WEDGETABLE ON cte_main.pname = WEDGETABLE.PLAYERNAME AND WEDGENUMBER = LINE_NUMBER
left OUTER JOIN WOODTABLE ON cte_main.pname = WOODTABLE.PLAYERNAME AND WOODNUMBER = LINE_NUMBER
left outer join PUTTERTABLE ON cte_main.pname = PUTTERTABLE.PLAYERNAME AND PUTTERNUMBER = LINE_NUMBER
left outer join BALLTABLE ON cte_main.pname = BALLTABLE.PLAYERNAME AND BALLNUMBER = LINE_NUMBER
left outer join
	(SELECT PLAYERNAME, SHAFTNUMBER AS IRONSHAFTNUMBER, [Shaft Club Code] as IRONSHAFTCLUBCODE, DCLUBCODE as DIRONSHAFTCLUBCODE, SHAFTMFGR AS IRONSHAFTMFGR, DSHAFTMFGRCODE AS DIRONSHAFTMFGR, SHAFTBRAND AS IRONSHAFTBRAND, DSHAFTBRANDCODE AS DIRONSHAFTBRAND,
	    SHAFTMODEL AS IRONSHAFTMODEL, DSHAFTMODELCODE AS DIRONSHAFTMODEL, SHAFTFLEX as IRONSHAFTFLEX, DSHAFTFLEX as DIRONSHAFTFLEX, SHAFTMATL AS IRONSHAFTMATL, DSHAFTMATLCODE AS DIRONSHAFTMATERIAL
        FROM SHAFTTABLE WHERE [Shaft Equip Type] = 'IRON') ironshaft 
ON cte_main.pname = ironshaft.PLAYERNAME AND IRONSHAFTNUMBER = LINE_NUMBER
left outer join
	(SELECT PLAYERNAME, SHAFTNUMBER AS WEDGESHAFTNUMBER, [Shaft Club Code] as WEDGESHAFTCLUBCODE, DCLUBCODE as DWEDGESHAFTCLUBCODE, SHAFTMFGR AS WEDGESHAFTMFGR, DSHAFTMFGRCODE AS DWEDGESHAFTMFGR, SHAFTBRAND AS WEDGESHAFTBRAND, DSHAFTBRANDCODE AS DWEDGESHAFTBRAND,
		SHAFTMODEL AS WEDGESHAFTMODEL, DSHAFTMODELCODE AS DWEDGESHAFTMODEL, SHAFTFLEX as WEDGESHAFTFLEX, DSHAFTFLEX as DWEDGESHAFTFLEX, SHAFTMATL AS WEDGESHAFTMATL, DSHAFTMATLCODE AS DWEDGESHAFTMATERIAL
		FROM SHAFTTABLE WHERE [Shaft Equip Type] = 'WEDG') wedgeshaft 
