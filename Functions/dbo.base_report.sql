			 (@WOODVAR = 3 and ISDRIVER = 0) or
			 (@WOODVAR = 4 and ISDRIVER = 0 and [Wood Club Code] <> 'HYB') OR
			 (@WOODVAR = 5 and [Wood Club Code] <> 'HYB')
		)
		
		
